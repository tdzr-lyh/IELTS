"""Build smaller speech MP3s without changing the recording, pitch or speed.

Generation needs ffmpeg (or imageio-ffmpeg). Deployment verification uses only
the standard library; original教材 MP3s remain unchanged as fallback sources.
"""

from __future__ import annotations

import argparse
import hashlib
import json
from pathlib import Path
import shutil
import subprocess

ROOT = Path(__file__).resolve().parent
OUTPUT = ROOT / "media" / "listening-lite"
MANIFEST = ROOT / "recording-audio.js"


def tracks() -> list[dict]:
    source = (ROOT / "listening-data.js").read_text(encoding="utf-8")
    return json.loads(source.split(" = ", 1)[1].strip().removesuffix(";"))["dictationTracks"]


def digest(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def verify_recording_audio() -> int:
    data = json.loads(MANIFEST.read_text(encoding="utf-8").split(" = ", 1)[1].strip().removesuffix(";"))
    if data.get("bitrate") != 64000 or data.get("channels") != 1:
        raise ValueError("Unexpected recording format")
    entries = data["clips"]
    if set(entries) != {track["id"] for track in tracks()}:
        raise ValueError("Recording manifest does not match the library")
    for track in tracks():
        entry = entries[track["id"]]
        target = ROOT / entry["url"].removeprefix("./")
        if OUTPUT not in target.resolve().parents:
            raise ValueError(f"Recording outside output directory: {target}")
        audio = target.read_bytes()
        if len(audio) != entry["bytes"] or len(audio) < 512:
            raise ValueError(f"Missing/truncated audio: {target}")
        if not (audio[:3] == b"ID3" or (audio[0] == 0xFF and audio[1] & 0xE0 == 0xE0)):
            raise ValueError(f"Invalid MP3: {target}")
        if hashlib.sha256(audio).hexdigest() != entry["sha256"]:
            raise ValueError(f"Recording checksum mismatch: {target}")
        original = ROOT / track["url"].removeprefix("./")
        if digest(original) != entry["sourceSha256"]:
            raise ValueError(f"Source updated; regenerate audio for {track['id']}")
    return len(entries)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    parser.add_argument("--ffmpeg")
    args = parser.parse_args()
    if args.check:
        print(f"Verified {verify_recording_audio()} optimized recordings")
        return
    ffmpeg = args.ffmpeg or shutil.which("ffmpeg")
    if not ffmpeg:
        import imageio_ffmpeg
        ffmpeg = imageio_ffmpeg.get_ffmpeg_exe()
    OUTPUT.mkdir(parents=True, exist_ok=True)
    clips = {}
    original_bytes = 0
    for track in tracks():
        original = ROOT / track["url"].removeprefix("./")
        source_hash = digest(original)
        target = OUTPUT / f"{track['id']}-{source_hash[:10]}.mp3"
        if not target.exists():
            subprocess.run([
                ffmpeg, "-hide_banner", "-loglevel", "error", "-y", "-i", str(original),
                "-map", "0:a:0", "-map_metadata", "-1", "-ac", "1", "-ar", "44100",
                "-codec:a", "libmp3lame", "-b:a", "64k", "-write_xing", "1", str(target),
            ], check=True)
        clips[track["id"]] = {
            "url": "./" + target.relative_to(ROOT).as_posix(),
            "bytes": target.stat().st_size,
            "sha256": digest(target),
            "sourceSha256": source_hash,
        }
        original_bytes += original.stat().st_size
    payload = {"version": 1, "bitrate": 64000, "channels": 1, "clips": clips}
    MANIFEST.write_text(
        "// Original recordings optimized for mobile; generated by build_recording_audio.py.\n"
        f"window.RECORDING_AUDIO = {json.dumps(payload, separators=(',', ':'))};\n",
        encoding="utf-8",
    )
    total = sum(entry["bytes"] for entry in clips.values())
    print(f"Recordings: {len(clips)}, {original_bytes:,} -> {total:,} bytes ({1-total/original_bytes:.1%} smaller)")
    verify_recording_audio()


if __name__ == "__main__":
    main()
